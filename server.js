// 업로드 API
app.post('/api/upload', upload.fields([
    { name: 'presetFile', maxCount: 1 },
    { name: 'thumbnailFile', maxCount: 1 }
]), async (req, res) => {
    let connection;
    try {
        if (!req.files || !req.files.presetFile) {
            return res.status(400).json({ error: '효과 파일이 업로드되지 않았습니다.' });
        }

        const presetFile = req.files.presetFile[0];
        const originalName = presetFile.originalname;
        const ext = path.extname(originalName).toLowerCase();

        if (ext !== '.ffx' && ext !== '.mogrt') {
            fs.unlinkSync(presetFile.path);
            if (req.files.thumbnailFile) fs.unlinkSync(req.files.thumbnailFile[0].path);
            return res.status(400).json({ error: '.ffx 또는 .mogrt 파일만 업로드할 수 있습니다.' });
        }

        const targetPresetPath = path.join(uploadDir, originalName);
        if (fs.existsSync(targetPresetPath)) fs.unlinkSync(targetPresetPath);
        fs.renameSync(presetFile.path, targetPresetPath);

        let thumbnailName = 'default-thumb.png';
        if (req.files.thumbnailFile) {
            const thumbFile = req.files.thumbnailFile[0];
            thumbnailName = Date.now() + '_' + thumbFile.originalname;
            const targetThumbPath = path.join(uploadDir, thumbnailName);
            fs.renameSync(thumbFile.path, targetThumbPath);
        }

        connection = await getConnection();
        await connection.execute(
            `INSERT INTO presets (name, thumbnail) VALUES (:name, :thumb)`,
            { name: originalName, thumb: thumbnailName },
            { autoCommit: true }
        );
        
        res.json({ success: true, message: '업로드 완료!' });
    } catch (err) {
        res.status(500).json({ error: err.message });
    } finally {
        if (connection) {
            try { await connection.close(); } catch (e) {}
        }
    }
});

// 목록 조회 API
app.get('/api/presets', async (req, res) => {
    let connection;
    try {
        connection = await getConnection();
        const result = await connection.execute(
            `SELECT id, name, thumbnail FROM presets ORDER BY id DESC`, 
            [], 
            { outFormat: oracledb.OUT_FORMAT_OBJECT }
        );
        res.json(result.rows);
    } catch (err) {
        res.json([]);
    } finally {
        if (connection) {
            try { await connection.close(); } catch (e) {}
        }
    }
});

// 파일 다운로드 API
app.get('/api/download/:filename', (req, res) => {
    const filename = req.params.filename;
    const filePath = path.join(uploadDir, filename);
    if (fs.existsSync(filePath)) {
        res.download(filePath, filename, (err) => {});
    } else {
        res.status(404).json({ error: '파일이 존재하지 않습니다.' });
    }
});

